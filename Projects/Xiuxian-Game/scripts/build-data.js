/**
 * build-data.js
 * 打包脚本：将 data/*.json 静态打包为 data-bundle.js
 * 解决浏览器在 file:// 协议下因 CORS 无法 fetch() 本地 JSON 的白屏阻断问题。
 *
 * 功能特性：
 * 1. 纯确定性构建：移除非确定性时间戳，采用 inputsHash (SHA-256) 防止 git diff 噪声。
 * 2. --check 模式：比对磁盘产物与源数据是否同步，不一致则 exit 1，防止静默漂移。
 * 3. 完整收拢：打包 world、tuning、stateTemplate、starters、npcs、text、items。
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

// 兼容从根目录运行或从可运行测试第一版目录运行
let baseDir = path.resolve(__dirname, '..', '可运行测试第一版');
if (!fs.existsSync(path.join(baseDir, 'data'))) {
  baseDir = path.resolve(__dirname, '..');
}
const dataDir = path.join(baseDir, 'data');
const outputFile = path.join(baseDir, 'data-bundle.js');

const isCheckMode = process.argv.includes('--check');

function loadJSON(filePath) {
  if (!fs.existsSync(filePath)) return null;
  const raw = fs.readFileSync(filePath, 'utf8');
  return JSON.parse(raw);
}

// 递归收集目录下的 json 文件
function loadJSONDirectory(dirPath) {
  const items = [];
  if (!fs.existsSync(dirPath)) return items;
  const files = fs.readdirSync(dirPath).filter(f => f.endsWith('.json')).sort();
  for (const file of files) {
    const data = loadJSON(path.join(dirPath, file));
    if (data) items.push(data);
  }
  return items;
}

// 收集所有数据源
const world = loadJSON(path.join(dataDir, 'world.json')) || {};
const tuning = loadJSON(path.join(dataDir, 'tuning.json')) || {};
const stateTemplate = loadJSON(path.join(dataDir, 'state-template.json')) || {};
const starters = loadJSONDirectory(path.join(dataDir, 'starters'));
const npcs = loadJSONDirectory(path.join(dataDir, 'npcs'));
const text = loadJSON(path.join(dataDir, 'text', 'narration.json')) || {};
const items = loadJSON(path.join(dataDir, 'items', 'items.json')) || [];

// 计算输入内容确定性哈希
const hash = crypto.createHash('sha256');
hash.update(JSON.stringify(world));
hash.update(JSON.stringify(tuning));
hash.update(JSON.stringify(stateTemplate));
hash.update(JSON.stringify(starters));
hash.update(JSON.stringify(npcs));
hash.update(JSON.stringify(text));
hash.update(JSON.stringify(items));
const inputsHash = 'sha256:' + hash.digest('hex');

const bundleData = {
  schemaVersion: '0.2',
  inputsHash,
  world,
  tuning,
  stateTemplate,
  starters,
  npcs,
  text,
  items
};

const outputContent = `/**
 * AUTO-GENERATED BUNDLE - DO NOT EDIT MANUALLY
 * Generated by scripts/build-data.js
 * Inputs Hash: ${inputsHash}
 * Provides offline data support for file:// double-click play.
 */
window.XIUXIAN_DATA = ${JSON.stringify(bundleData, null, 2)};
`;

if (isCheckMode) {
  if (!fs.existsSync(outputFile)) {
    console.error(`[build-data --check] ❌ Output bundle "${outputFile}" does not exist on disk!`);
    console.error(`Run "node scripts/build-data.js" to build.`);
    process.exit(1);
  }

  const diskContent = fs.readFileSync(outputFile, 'utf8').replace(/\r\n/g, '\n');
  const normalizedOutput = outputContent.replace(/\r\n/g, '\n');

  if (diskContent !== normalizedOutput) {
    console.error(`[build-data --check] ❌ Drift detected: "${outputFile}" is out of sync with data/*.json!`);
    console.error(`Run "node scripts/build-data.js" to regenerate data-bundle.js.`);
    process.exit(1);
  }

  console.log(`[build-data --check] ✅ data-bundle.js is perfectly in sync with data/*.json (hash: ${inputsHash.substring(0, 15)}...).`);
  process.exit(0);
} else {
  fs.writeFileSync(outputFile, outputContent, 'utf8');
  console.log(`[build-data] ✅ Data successfully bundled to ${outputFile}`);
  console.log(`             Inputs Hash: ${inputsHash}`);
  console.log(`             Contents: ${starters.length} starters, ${npcs.length} npcs, ${items.length} items, ${world.locations ? world.locations.length : 0} locations.`);
}
